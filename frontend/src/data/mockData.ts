export function computeScenarioData(
  scenario: DemoScenario,
  baseUnits = INITIAL_STORAGE_UNITS,
  baseAlerts = INITIAL_ALERTS,
  basePests = INITIAL_PEST_DETECTIONS,
  baseRecs = INITIAL_RECOMMENDATIONS,
  baseIntvs = INITIAL_INTERVENTIONS
) {
  const units = JSON.parse(JSON.stringify(baseUnits)) as StorageUnit[];
  const alerts = JSON.parse(JSON.stringify(baseAlerts)) as Alert[];
  const pests = JSON.parse(JSON.stringify(basePests)) as PestDetection[];
  const recs = JSON.parse(JSON.stringify(baseRecs)) as Recommendation[];
  const intvs = JSON.parse(JSON.stringify(baseIntvs)) as Intervention[];

  if (scenario === 'normal') {
    units.forEach((u) => {
      u.health_status = 'healthy';
      u.risk_score = Math.min(26, u.risk_score);
      u.zones.forEach((z) => {
        z.health_status = 'healthy';
        z.risk_score = Math.min(24, z.risk_score);
        z.temperature = Number(Math.min(z.temperature, 27.2).toFixed(1));
        z.humidity = Number(Math.min(z.humidity, 56.5).toFixed(1));
        z.moisture = Number(Math.min(z.moisture, 12.0).toFixed(1));
        z.co2 = Number(Math.min(z.co2, 510.0).toFixed(0));
        z.pest_detected = false;
        z.pest_type = null;
        z.pest_probability = 0.04;
      });
    });
    alerts.forEach((a, i) => {
      if (i < 5) a.status = 'resolved';
    });
  } else if (scenario === 'humidity') {
    units.forEach((u) => {
      if (u.id === 'WH-001' || u.id === 'WH-002') {
        u.health_status = 'warning';
        u.risk_score = 68;
        u.zones.forEach((z) => {
          z.humidity = Number((z.humidity + 12.5).toFixed(1));
          z.moisture = Number((z.moisture + 2.0).toFixed(1));
          z.risk_score = Math.min(80, z.risk_score + 28);
          z.health_status = 'warning';
        });
      }
    });
  } else if (scenario === 'pest') {
    units.forEach((u) => {
      if (u.id === 'SL-001' || u.id === 'WH-001') {
        u.health_status = u.id === 'SL-001' ? 'critical' : 'warning';
        u.risk_score = u.id === 'SL-001' ? 82 : 68;
        u.zones.forEach((z) => {
          if (z.id.includes('Z1') || z.id.includes('Z2')) {
            z.pest_detected = true;
            z.pest_probability = 0.92;
            z.pest_type = 'Lesser Grain Borer (Rhyzopertha dominica)';
            z.risk_score = 84;
            z.health_status = 'critical';
          }
        });
      }
    });
  } else if (scenario === 'critical') {
    units.forEach((u) => {
      if (u.id === 'SL-001' || u.id === 'WH-001') {
        u.health_status = 'critical';
        u.risk_score = 91;
        u.zones.forEach((z) => {
          z.temperature = 34.8;
          z.humidity = 78.5;
          z.moisture = 15.9;
          z.co2 = 1250;
          z.risk_score = 94;
          z.health_status = 'critical';
          z.pest_detected = true;
          z.pest_type = 'Lesser Grain Borer (Rhyzopertha dominica)';
          z.pest_probability = 0.97;
        });
      }
    });
  }

  const allZones = units.flatMap((u) => u.zones);
  const totalQuantity = units.reduce((acc, u) => acc + u.current_quantity_mt, 0);
  const healthyCount = allZones.filter((z) => z.health_status === 'healthy').length;
  const atRiskCount = allZones.filter((z) => z.health_status !== 'healthy').length;
  const activePestsCount = allZones.filter((z) => z.pest_detected).length;
  const avgRisk = Number(
    (units.reduce((acc, u) => acc + u.risk_score, 0) / units.length).toFixed(1)
  );

  const kpis: OverviewKPIs = {
    total_storage_units: units.length,
    total_grain_stored_mt: totalQuantity,
    healthy_zones: healthyCount,
    at_risk_zones: atRiskCount,
    active_pest_detections: activePestsCount,
    average_storage_risk: avgRisk,
  };

  return { units, alerts, pests, recs, intvs, kpis };
}

