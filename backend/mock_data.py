def get_scenario_data(scenario: str) -> Dict[str, Any]:
    """
    Returns modified data corresponding to 4 demo scenarios:
    1. 'normal': Normal Storage Conditions
    2. 'humidity': Rising Humidity
    3. 'pest': Suspected Pest Activity
    4. 'critical': Critical Storage Risk
    """
    import copy
    units = copy.deepcopy(BASE_STORAGE_UNITS)
    alerts = copy.deepcopy(BASE_ALERTS)
    pests = copy.deepcopy(BASE_PEST_DETECTIONS)
    recs = copy.deepcopy(BASE_RECOMMENDATIONS)
    interventions = copy.deepcopy(BASE_INTERVENTIONS)

    if scenario == "normal":
        # All units healthy, risk scores below 30
        for u in units:
            u["health_status"] = "healthy"
            u["risk_score"] = min(28, u["risk_score"])
            for z in u["zones"]:
                z["health_status"] = "healthy"
                z["risk_score"] = min(25, z["risk_score"])
                z["temperature"] = round(min(z["temperature"], 27.5), 1)
                z["humidity"] = round(min(z["humidity"], 58.0), 1)
                z["moisture"] = round(min(z["moisture"], 12.2), 1)
                z["co2"] = round(min(z["co2"], 520.0), 1)
                z["pest_detected"] = False
                z["pest_type"] = None
                z["pest_probability"] = 0.04
        # Mark alerts resolved
        for a in alerts[:4]:
            a["status"] = "resolved"

    elif scenario == "humidity":
        # WH-001 and WH-002 showing high humidity creep
        for u in units:
            if u["id"] in ["WH-001", "WH-002"]:
                u["health_status"] = "warning"
                u["risk_score"] = 68
                for z in u["zones"]:
                    z["humidity"] = round(z["humidity"] + 12.5, 1)
                    z["moisture"] = round(z["moisture"] + 2.1, 1)
                    z["risk_score"] = min(80, z["risk_score"] + 30)
                    z["health_status"] = "warning"

    elif scenario == "pest":
        # Silo 01 and WH-001 show high acoustic insect activity
        for u in units:
            if u["id"] in ["SL-001", "WH-001"]:
                u["health_status"] = "warning"
                u["risk_score"] = 72
                for z in u["zones"]:
                    if "Z1" in z["id"] or "Z2" in z["id"]:
                        z["pest_detected"] = True
                        z["pest_probability"] = 0.94
                        z["pest_type"] = "Lesser Grain Borer (Rhyzopertha dominica)"
                        z["risk_score"] = 78
                        z["health_status"] = "warning"

    elif scenario == "critical":
        # SL-001 and WH-001 in critical risk
        for u in units:
            if u["id"] in ["SL-001", "WH-001"]:
                u["health_status"] = "critical"
                u["risk_score"] = 89
                for z in u["zones"]:
                    z["temperature"] = 34.8
                    z["humidity"] = 78.5
                    z["moisture"] = 15.9
                    z["co2"] = 1250.0
                    z["risk_score"] = 92
                    z["health_status"] = "critical"
                    z["pest_detected"] = True
                    z["pest_type"] = "Lesser Grain Borer (Rhyzopertha dominica)"
                    z["pest_probability"] = 0.96

    # Calculate aggregate KPIs
    total_stored = sum(u["current_quantity_mt"] for u in units)
    total_units = len(units)
    all_zones = [z for u in units for z in u["zones"]]
    healthy_zones = sum(1 for z in all_zones if z["health_status"] == "healthy")
    at_risk_zones = sum(1 for z in all_zones if z["health_status"] in ["warning", "critical"])
    active_pests = sum(1 for z in all_zones if z["pest_detected"])
    avg_risk = round(sum(u["risk_score"] for u in units) / total_units, 1)

    kpis = {
        "total_storage_units": total_units,
        "total_grain_stored_mt": total_stored,
        "healthy_zones": healthy_zones,
        "at_risk_zones": at_risk_zones,
        "active_pest_detections": active_pests,
        "average_storage_risk": avg_risk,
    }

    return {
        "scenario": scenario,
        "facility": FACILITY_INFO,
        "kpis": kpis,
        "storage_units": units,
        "alerts": alerts,
        "pest_detections": pests,
        "recommendations": recs,
        "interventions": interventions,
    }

